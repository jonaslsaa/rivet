#!/usr/bin/env python3
"""Shared, offline Rust-source scanning helpers for the progress ledgers.

Used by scripts/coverage_ledger.py (COVERAGE.tsv), scripts/verify_ledger.py
(VERIFY.tsv) and scripts/verify_debt.py. Everything here is a lexical
heuristic, not a Rust parser:

- `blank_comments_and_strings` replaces comment and string/char-literal bytes
  with spaces (newlines kept), so byte offsets and line numbers are unchanged
  and later regexes never match inside comments or literals. Nested block
  comments are not tracked (rare in this tree).
- `test_ranges` finds items annotated `#[cfg(test)]` (or `#[cfg(all(test, ..))]`)
  and returns the byte range of each item: from the attribute through the
  matching `}` of the item's first `{`, or through its `;` (`mod tests;`).
- `is_test_file` / `is_generated_path` / `has_generated_header` define the
  files that are never production source (VERIFICATION.md section 4.1).
"""

import re
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

_RUST_LEX_RE = re.compile(
    r"//[^\n]*"  # line comment (incl. doc comments)
    r"|/\*.*?\*/"  # block comment
    r'|b?r(#*)".*?"\1'  # raw (byte) string
    r'|b?"(?:\\.|[^"\\])*"'  # (byte) string
    r"|b?'(?:\\(?:u\{[0-9A-Fa-f]{1,6}\}|x[0-9A-Fa-f]{2}|.)|[^'\\\n])'",  # char literal
    re.S,
)

_CFG_TEST_RE = re.compile(r"#\[cfg\((?:all\(\s*)?test\b[^\]]*\]")
FN_RE = re.compile(r"\bfn\s+((?:r#)?[A-Za-z_][A-Za-z0-9_]*)")
TODO_MACRO_RE = re.compile(r"\b(?:todo|unimplemented)!\s*[\(\[\{]")


def _blank(m: re.Match) -> str:
    return "\n".join(" " * len(part) for part in m.group(0).split("\n"))


def blank_comments_and_strings(text: str) -> str:
    """Same-length copy of `text` with comments and literals blanked."""
    return _RUST_LEX_RE.sub(_blank, text)


def _match_brace(code: str, open_idx: int) -> int:
    """Index of the `}` matching the `{` at open_idx (or len-1 if unbalanced)."""
    depth = 0
    for i in range(open_idx, len(code)):
        c = code[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i
    return len(code) - 1


def test_ranges(code: str) -> list[tuple[int, int]]:
    """Byte ranges [start, end) of `#[cfg(test)]` items in blanked code."""
    ranges: list[tuple[int, int]] = []
    pos = 0
    while True:
        m = _CFG_TEST_RE.search(code, pos)
        if not m:
            break
        start = m.start()
        i = m.end()
        # First `{` or `;` after the attribute ends/opens the item.
        brace = code.find("{", i)
        semi = code.find(";", i)
        if brace == -1 and semi == -1:
            break
        if semi != -1 and (brace == -1 or semi < brace):
            end = semi + 1
        else:
            end = _match_brace(code, brace) + 1
        ranges.append((start, end))
        pos = end
    return ranges


def strip_test_code(code: str) -> str:
    """Blank out every `#[cfg(test)]` item (newlines kept)."""
    out = list(code)
    for start, end in test_ranges(code):
        for i in range(start, end):
            if out[i] != "\n":
                out[i] = " "
    return "".join(out)


def production_line_count(text: str) -> int:
    """Lines of `text` outside `#[cfg(test)]` items (blank lines included,
    matching the plain line counts the plan documents use)."""
    code = blank_comments_and_strings(text)
    total = text.count("\n") + (0 if text.endswith("\n") or not text else 1)
    removed = 0
    for start, end in test_ranges(code):
        removed += code.count("\n", start, end)
    return max(total - removed, 0)


def fn_names(code: str) -> list[str]:
    """`fn` names in blanked, test-stripped code (raw `r#` prefix kept)."""
    return FN_RE.findall(code)


def is_test_file(rel: Path) -> bool:
    name = rel.name
    if name == "tests.rs" or name.endswith("_tests.rs") or name.endswith("_test.rs"):
        return True
    return "tests" in rel.parts or "benches" in rel.parts or "examples" in rel.parts


def is_generated_path(rel: Path) -> bool:
    return "generated" in rel.parts


_GENERATED_HEADER_RE = re.compile(
    r"^\s*//[/!]?.*(?:@generated|\bGENERATED\b|\bGenerated by\b|do not hand-edit)", re.M)


def has_generated_header(text: str) -> bool:
    """A codegen header in the first five lines (`@generated`, `GENERATED`,
    `Generated by`, `do not hand-edit`)."""
    head = "\n".join(text.splitlines()[:5])
    return _GENERATED_HEADER_RE.search(head) is not None


_MOD_DECL_RE = re.compile(r"\bmod\s+(?:r#)?([A-Za-z_][A-Za-z0-9_]*)\s*;")
_MOD_PREFIX_RE = re.compile(r"((?:#\[[^\]]*\]\s*)*)(?:pub(?:\([^)]*\))?\s+)?\Z")
_PATH_ATTR_RE = re.compile(r'#\[\s*path\s*=\s*"([^"]+)"\s*\]')
_CRATE_ROOT_RE = re.compile(r"^((?:crates|tools)/[^/]+/src)/(?:lib\.rs|main\.rs|bin/[^/]+\.rs|bin/[^/]+/main\.rs)$")


class ModuleInfo:
    """Where a source file sits in its crate's module tree."""
    __slots__ = ("root", "path", "test_only", "parent")

    def __init__(self, root: str, path: tuple[str, ...], test_only: bool, parent: str | None):
        self.root = root  # crate root file, e.g. crates/x/src/lib.rs
        self.path = path  # module path below the crate root
        self.test_only = test_only  # declared under #[cfg(test)] here or in an ancestor
        self.parent = parent  # file holding the `mod` declaration (None for a root)


_INCLUDE_RE = re.compile(r'\binclude!\s*\(\s*"([^"]+\.rs)"\s*\)')


def _includes(text: str, code: str) -> list[tuple[str, bool]]:
    """(path, inside a #[cfg(test)] item?) of each `include!("x.rs")`;
    `code` is `text` with comments and literals blanked."""
    out = []
    tests = None
    if "include!" not in text:
        return out
    for m in _INCLUDE_RE.finditer(text):
        if code[m.start():m.start() + 8] != "include!":
            continue  # inside a comment or literal
        if tests is None:
            tests = test_ranges(code)
        out.append((m.group(1), any(a <= m.start() < b for a, b in tests)))
    return out


def _top_level_mod_decls(text: str, code: str) -> list[tuple[str, str]]:
    """(name, attribute text) of the file's top-level `mod x;` declarations
    (inline `mod y { mod z; }` nesting is skipped); `code` is `text` with
    comments and literals blanked."""
    braces = [(m.start(), 1 if m.group() == "{" else -1) for m in re.finditer(r"[{}]", code)]
    out = []
    bi = 0
    depth = 0
    for m in _MOD_DECL_RE.finditer(code):
        while bi < len(braces) and braces[bi][0] < m.start():
            depth = max(depth + braces[bi][1], 0)
            bi += 1
        if depth == 0:
            # The attributes before `[pub] mod`, read from the original text
            # (same offsets) so a `#[path = "..."]` string survives blanking.
            lo = max(m.start() - 1000, 0)
            pre = _MOD_PREFIX_RE.search(code, lo, m.start())
            out.append((m.group(1), text[pre.start(1):pre.end(1)] if pre else ""))
    return out


def module_map(files: set[str], read) -> dict[str, ModuleInfo]:
    """Module tree of every crate in `files` (repo paths), walked from each
    crate root (`src/lib.rs`, `src/main.rs`, `src/bin/*`) through the
    top-level `mod x;` declarations, honouring `#[path = "..."]` (relative to
    the declaring file's directory; the loaded file then resolves its own
    children like a `mod.rs`) and `#[cfg(test)]`. A file spliced in with
    `include!("x.rs")` takes the including file's module path (the inline
    `mod` it may sit in is not tracked), and is test-only when the include
    sits in a `#[cfg(test)]` item. `read(path)` returns a file's text. Files no
    declaration reaches are absent from the map."""
    info: dict[str, ModuleInfo] = {}

    def visit(path: str, root: str, modpath: tuple[str, ...], test_only: bool, mod_rs_like: bool) -> None:
        here = path.rsplit("/", 1)[0]
        child_dir = here if mod_rs_like else path[: -len(".rs")]
        text = read(path)
        code = blank_comments_and_strings(text)
        for name, attrs in _top_level_mod_decls(text, code):
            test = test_only or _CFG_TEST_RE.search(attrs) is not None
            explicit = _PATH_ATTR_RE.search(attrs)
            if explicit:
                cands = [Path(here, explicit.group(1)).as_posix()]
            else:
                cands = [f"{child_dir}/{name}.rs", f"{child_dir}/{name}/mod.rs"]
            for cand in cands:
                cand = _normpath(cand)
                if cand in files and cand not in info:
                    info[cand] = ModuleInfo(root, modpath + (name,), test, path)
                    visit(cand, root, modpath + (name,), test,
                          bool(explicit) or cand.endswith("/mod.rs"))
                    break
        # `include!("x.rs")` splices x.rs into this module.
        for rel, in_test in _includes(text, code):
            cand = _normpath(f"{here}/{rel}")
            if cand in files and cand not in info:
                info[cand] = ModuleInfo(root, modpath, test_only or in_test, path)

    for path in sorted(files):
        if _CRATE_ROOT_RE.match(path) and path not in info:
            info[path] = ModuleInfo(path, (), False, None)
            visit(path, path, (), False, True)
    return info


def _normpath(path: str) -> str:
    parts: list[str] = []
    for seg in path.split("/"):
        if seg == "..":
            if parts:
                parts.pop()
        elif seg and seg != ".":
            parts.append(seg)
    return "/".join(parts)


def tracked_crate_sources() -> list[Path]:
    """git-tracked `crates/*/src/**/*.rs`, sorted, repo-relative."""
    out = subprocess.run(
        ["git", "ls-files", "-z", "--", "crates/*/src/*.rs", "crates/*/src/**/*.rs"],
        cwd=REPO,
        capture_output=True,
        text=True,
        check=True,
    )
    paths = {Path(p) for p in out.stdout.split("\0") if p}
    return sorted(paths)
