#!/usr/bin/env python3
"""Verification debt: how much ported Rust has no Java-sourced check (VERIFICATION.md 4.1).

Run:  python3 scripts/verify_debt.py                    # debt table + top-20 V0 files
      python3 scripts/verify_debt.py --tsv OUT          # also write the table as TSV
      python3 scripts/verify_debt.py --baseline OLD.tsv # add debt_delta vs a previous --tsv
      python3 scripts/verify_debt.py --check            # exit 1 only on malformed ledgers

Deterministic and offline: reads VERIFY.tsv, COVERAGE.tsv (validated only) and
the git-tracked crate sources.

Unit of account: production LOC of each `crates/*/src/**/*.rs` file, i.e. its
lines minus `#[cfg(test)]` items (scripts/rust_scan.py). Excluded entirely:
test files (`tests.rs`, `*_test(s).rs`, `tests/`), test-only modules (a module
its parent declares under `#[cfg(test)]`, e.g. `*_fixture.rs`), `generated/`
trees, files with a codegen header (`@generated`, `GENERATED`, `Generated by`,
`do not hand-edit` in the first five lines: the Mth and Unicode tables), and
the `rivet-test-support` crate.

Classes, from the VERIFY.tsv rows whose `rust_globs` match a file:
  V2  a PASS row at L2-L6 with a negative control (negative = y)
  V1  a PASS row at L1 (recorded Paper golden consumed by cargo tests)
  V0  everything else (no PASS Java-sourced row, or beyond a row's cap)
Corpus cap: a row credits at most K * corpus_n LOC (K = 50); a row with no
countable corpus (`-`) credits nothing. Allocation is greedy and
deterministic: V2 rows first, then V1 rows, each in id order, each spending
its budget over its matched files in path order on LOC not yet credited.
A file can therefore be split across classes.

Outputs per subsystem (SUBSYSTEMS, first matching path prefix) and in total:
  loc, v2_loc, thin_loc (= V1), debt_loc (= V0), debt_ratio (= V0 / loc),
  and debt_delta when --baseline is given; then the top 20 files by V0 LOC
  (the verification backlog). The VERIFICATION 4.2 thresholds are reported,
  not enforced: a subsystem is flagged `pause` when debt_ratio > 0.30 and
  debt_loc > 10,000, and the global line says whether debt_ratio > 0.35.

`--check` fails only on malformed ledgers: a VERIFY.tsv or COVERAGE.tsv that
does not parse, breaks verify_ledger.validate, or names a rust glob that
matches no tracked file.
"""

import argparse
import csv
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import coverage_ledger  # noqa: E402
import rust_scan  # noqa: E402
import verify_ledger  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
K = 50
SUBSYSTEM_PAUSE_RATIO = 0.30
SUBSYSTEM_PAUSE_LOC = 10_000
GLOBAL_PAUSE_RATIO = 0.35

