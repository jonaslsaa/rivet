EXCLUDED_CRATES = {"rivet-test-support"}


def glob_regex(glob: str) -> re.Pattern:
    out = ""
    i = 0
    while i < len(glob):
        if glob.startswith("**", i):
            out += ".*"
            i += 2
        elif glob[i] == "*":
            out += "[^/]*"
            i += 1
        elif glob[i] == "?":
            out += "[^/]"
            i += 1
        else:
            out += re.escape(glob[i])
            i += 1
    return re.compile(out + r"\Z")


def subsystem_of(path: str) -> str:
    for prefix, name in SUBSYSTEMS:
        if path.startswith(prefix):
            return name
    return "other"


def production_files() -> dict[str, int]:
    """repo path -> production LOC for every file in the unit of account."""
    tracked = verify_ledger.git_files()
    tree = verify_ledger.RustTree(tracked)
    out = {}
    for rel in rust_scan.tracked_crate_sources():
        path = rel.as_posix()
        if rel.parts[1] in EXCLUDED_CRATES or rust_scan.is_generated_path(rel):
            continue
        text = (REPO / rel).read_text(encoding="utf-8", errors="replace")
        if rust_scan.has_generated_header(text) or tree.is_test_only(path, text):
            continue
        loc = rust_scan.production_line_count(text)
        if loc:
            out[path] = loc
    return out


def load_verify(path: Path) -> tuple[list[dict[str, str]], list[str]]:
    text = path.read_text(encoding="utf-8")
    errors = verify_ledger.validate(text)
    rows = list(csv.DictReader(text.splitlines(), delimiter="\t", quoting=csv.QUOTE_NONE))
    return rows, errors


def validate_coverage(path: Path) -> list[str]:
    errors = []
    with path.open(newline="", encoding="utf-8") as fh:
        reader = csv.reader(fh, delimiter="\t", quoting=csv.QUOTE_NONE)
        header = next(reader, None)
        if header != coverage_ledger.COLUMNS:
            return [f"{path.name}: header does not match coverage_ledger.COLUMNS"]
        statuses = {"absent", "partial", "complete", *coverage_ledger.NON_TARGET_STATUS.values()}
        for n, cells in enumerate(reader, start=2):
            if len(cells) != len(header):
                errors.append(f"{path.name}:{n}: {len(cells)} cells, expected {len(header)}")
            elif cells[-1] not in statuses:
                errors.append(f"{path.name}:{n}: bad status {cells[-1]}")
    return errors


def row_class(r: dict[str, str]) -> str | None:
    if r["status"] != "PASS":
        return None
    if r["layer"] in {"L2", "L3", "L4", "L5", "L6"} and r["negative"] == "y":
        return "V2"
    if r["layer"] == "L1":
        return "V1"
    return None


def allocate(rows: list[dict[str, str]], files: dict[str, int]) -> tuple[dict, dict, list[str]]:
    """Per-file V2/V1 credit, and the globs that match no tracked file."""
    tracked = set(verify_ledger.git_files())
    credit = {"V2": defaultdict(int), "V1": defaultdict(int)}
    dead = []
    remaining = dict(files)
    for cls in ("V2", "V1"):
        for r in sorted(rows, key=lambda r: r["id"]):
            globs = [] if r["rust_globs"] == "-" else r["rust_globs"].split(";")
            regexes = [glob_regex(g) for g in globs]
            for g, rx in zip(globs, regexes):
                if not any(rx.match(t) for t in tracked):
                    dead.append(f"{r['id']}: {g}")
            if row_class(r) != cls:
                continue
            budget = K * int(r["corpus_n"]) if r["corpus_n"].isdigit() else 0
            for path in sorted(p for p in files if any(rx.match(p) for rx in regexes)):
                if budget <= 0:
                    break
                take = min(budget, remaining[path])
                credit[cls][path] += take
                remaining[path] -= take
                budget -= take
    return credit["V2"], credit["V1"], sorted(set(dead))


def table(files: dict[str, int], v2: dict, v1: dict) -> dict[str, dict[str, int]]:
    agg: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for path, loc in files.items():
        for key in (subsystem_of(path), "TOTAL"):
            a = agg[key]
            a["files"] += 1
            a["loc"] += loc
            a["v2_loc"] += v2.get(path, 0)
            a["thin_loc"] += v1.get(path, 0)
            a["debt_loc"] += loc - v2.get(path, 0) - v1.get(path, 0)
    return agg


def load_baseline(path: Path) -> dict[str, int]:
    with path.open(newline="", encoding="utf-8") as fh:
        return {r["subsystem"]: int(r["debt_loc"]) for r in csv.DictReader(fh, delimiter="\t")}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 only on malformed ledgers")
    ap.add_argument("--tsv", type=Path, help="write the per-subsystem table as TSV")
    ap.add_argument("--baseline", type=Path, help="a previous --tsv output, for debt_delta")
    ap.add_argument("--verify", type=Path, default=REPO / "VERIFY.tsv")
    ap.add_argument("--coverage", type=Path, default=REPO / "COVERAGE.tsv")
    args = ap.parse_args()

    rows, errors = load_verify(args.verify)
    errors += validate_coverage(args.coverage)
    files = production_files()
    v2, v1, dead = allocate(rows, files)
    errors += [f"VERIFY.tsv: rust glob matches no tracked file: {d}" for d in dead]
    if args.check:
        for e in errors:
            print(e, file=sys.stderr)
        if errors:
            return 1
        print(f"ledgers well-formed ({len(rows)} VERIFY rows, {len(files)} production files)")
        return 0
    for e in errors:
        print(f"warning: {e}", file=sys.stderr)

    agg = table(files, v2, v1)
    base = load_baseline(args.baseline) if args.baseline else None
    keys = sorted(k for k in agg if k != "TOTAL") + ["TOTAL"]
    cols = ["subsystem", "files", "loc", "v2_loc", "thin_loc", "debt_loc", "debt_ratio"]
    if base is not None:
        cols.append("debt_delta")
    cols.append("flag")
    lines = ["\t".join(cols)]
    for k in keys:
        a = agg[k]
        ratio = a["debt_loc"] / a["loc"] if a["loc"] else 0.0
        if k == "TOTAL":
            flag = "global-pause" if ratio > GLOBAL_PAUSE_RATIO else "-"
        else:
            flag = "pause" if ratio > SUBSYSTEM_PAUSE_RATIO and a["debt_loc"] > SUBSYSTEM_PAUSE_LOC else "-"
        cells = [k, str(a["files"]), str(a["loc"]), str(a["v2_loc"]), str(a["thin_loc"]),
                 str(a["debt_loc"]), f"{ratio:.3f}"]
        if base is not None:
            cells.append(str(a["debt_loc"] - base.get(k, 0)))
        cells.append(flag)
        lines.append("\t".join(cells))
    out = "\n".join(lines) + "\n"
    if args.tsv:
        args.tsv.write_text(out, encoding="utf-8")
    widths = [max(len(line.split("\t")[i]) for line in lines) for i in range(len(cols))]
    for line in lines:
        print("  ".join(c.ljust(w) if i == 0 else c.rjust(w)
                        for i, (c, w) in enumerate(zip(line.split("\t"), widths))))
    print(f"\nthresholds (reported, not enforced): subsystem pause when debt_ratio > "
          f"{SUBSYSTEM_PAUSE_RATIO} and debt_loc > {SUBSYSTEM_PAUSE_LOC}; global pause when "
          f"debt_ratio > {GLOBAL_PAUSE_RATIO}. K = {K} LOC per corpus input.")
    print("\ntop 20 V0 files (verification backlog):")
    v0 = sorted(((files[p] - v2.get(p, 0) - v1.get(p, 0), p) for p in files), key=lambda t: (-t[0], t[1]))
    for loc, path in v0[:20]:
        print(f"  {loc:6d}  {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
