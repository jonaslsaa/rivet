//! LevelTicks over canonical chunk-owned containers. A registration is an
//! index, never a copied queue or a second owner of the chunk's ticks.
use super::{LevelChunkTicks, ScheduledTick, UniqueTickKey};
use crate::levelgen::structure::BoundingBox;
use rivet_registry::core::{BlockPos, ChunkPos, Vec3i};
use rivet_util::long2long_open_hash_map::Long2LongOpenHashMap;
use std::{
    cmp::Ordering,
    collections::{HashSet, VecDeque},
    hash::Hash,
    sync::{Arc, Mutex},
};

#[cfg(test)]
