/// Borrowed access to the actual loaded chunk containers. Registration and
/// removal must accompany canonical chunk installation/removal. A provider
/// must not silently substitute a detached queue for a missing chunk.
pub trait TickContainers<T> {
    fn get(&self, pos: ChunkPos) -> Option<&LevelChunkTicks<T>>;
    fn get_mut(&mut self, pos: ChunkPos) -> Option<&mut LevelChunkTicks<T>>;
}

pub struct LevelTicks<T> {
    registered: HashSet<i64>,
    next: Arc<Mutex<Long2LongOpenHashMap>>,
    containers_to_tick: Vec<ChunkPos>,
    to_run: VecDeque<ScheduledTick<T>>,
    already_run: Vec<ScheduledTick<T>>,
    to_run_set: HashSet<UniqueTickKey<T>>,
}
impl<T> Default for LevelTicks<T> {
    fn default() -> Self {
        Self {
            registered: HashSet::new(),
            next: Arc::new(Mutex::new(Long2LongOpenHashMap::default())),
            containers_to_tick: Vec::new(),
            to_run: VecDeque::new(),
            already_run: Vec::new(),
            to_run_set: HashSet::new(),
        }
    }
}
fn unpack(key: i64) -> ChunkPos {
    ChunkPos::new(ChunkPos::get_x(key), ChunkPos::get_z(key))
}
impl<T: Clone + Eq + Hash + 'static> LevelTicks<T> {
    pub fn new() -> Self {
        Self::default()
    }
    pub fn has_container(&self, pos: ChunkPos) -> bool {
        self.registered.contains(&pos.pack())
    }
    /// Registration deliberately does not unpack saved ticks. Paper unpacks
    /// them only when ServerLevel.startTickingChunk activates the chunk.
    pub fn add_container(&mut self, pos: ChunkPos, container: &mut LevelChunkTicks<T>) {
        self.registered.insert(pos.pack());
        if let Some(head) = container.peek() {
            self.next
                .lock()
                .unwrap_or_else(|poisoned| poisoned.into_inner())
                .put(pos.pack(), head.trigger_tick);
        }
        let next = Arc::clone(&self.next);
        container.set_on_tick_added(Some(Arc::new(move |container, added| {
            if container.peek() == Some(added) {
                next.lock()
                    .unwrap_or_else(|poisoned| poisoned.into_inner())
                    .put(ChunkPos::pack_block_pos(&added.pos), added.trigger_tick);
            }
        })));
    }
    pub fn remove_container(&mut self, pos: ChunkPos, container: &mut LevelChunkTicks<T>) {
        self.registered.remove(&pos.pack());
        self.next
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
            .remove(pos.pack());
        container.set_on_tick_added(None);
    }
    /// False is Paper's logAndPauseIfInIde/unloaded-position drop, not a
    /// successful schedule. No chunk is loaded or generated by this method.
    pub fn schedule(&mut self, store: &mut impl TickContainers<T>, tick: ScheduledTick<T>) -> bool {
        let pos = ChunkPos::containing(&tick.pos);
        if self.registered.contains(&pos.pack())
            && let Some(container) = store.get_mut(pos)
        {
            container.schedule(tick);
            return true;
        }
        rivet_util::log_and_pause_if_in_ide(&format!(
            "Trying to schedule tick in not loaded position {:?}",
            tick.pos
        ));
        false
    }
    fn update_container_scheduling(&self, tick: &ScheduledTick<T>) {
        self.next
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
            .put(ChunkPos::pack_block_pos(&tick.pos), tick.trigger_tick);
    }
    fn compare(store: &impl TickContainers<T>, a: ChunkPos, b: ChunkPos) -> Ordering {
        ScheduledTick::intra_tick_drain_cmp(
            store
                .get(a)
                .and_then(LevelChunkTicks::peek)
                .expect("queued container lost head"),
            store
                .get(b)
                .and_then(LevelChunkTicks::peek)
                .expect("queued container lost head"),
        )
    }
    // java.util.PriorityQueue with its exact equal-comparator behavior.
    fn offer_container(&mut self, store: &impl TickContainers<T>, pos: ChunkPos) {
        self.containers_to_tick.push(pos);
        let mut child = self.containers_to_tick.len() - 1;
        while child > 0 {
            let parent = (child - 1) >> 1;
            if Self::compare(
                store,
                self.containers_to_tick[child],
                self.containers_to_tick[parent],
            ) != Ordering::Less
            {
                break;
            }
            self.containers_to_tick.swap(child, parent);
            child = parent;
        }
    }
    fn poll_container(&mut self, store: &impl TickContainers<T>) -> Option<ChunkPos> {
        if self.containers_to_tick.is_empty() {
            return None;
        }
        let result = self.containers_to_tick.swap_remove(0);
        let len = self.containers_to_tick.len();
        let mut parent = 0;
        while parent < len / 2 {
            let mut child = parent * 2 + 1;
            if child + 1 < len
                && Self::compare(
                    store,
                    self.containers_to_tick[child],
                    self.containers_to_tick[child + 1],
                ) == Ordering::Greater
            {
                child += 1;
            }
            if Self::compare(
                store,
                self.containers_to_tick[parent],
                self.containers_to_tick[child],
            ) != Ordering::Greater
            {
                break;
            }
            self.containers_to_tick.swap(parent, child);
            parent = child;
        }
        Some(result)
    }
    fn can_schedule_more(&self, max: i32) -> bool {
        (self.to_run.len() as i64) < i64::from(max)
    }
    fn collect_ticks(
        &mut self,
        store: &mut impl TickContainers<T>,
        current: i64,
        max: i32,
        mut check: impl FnMut(ChunkPos) -> bool,
    ) {
        // Entry iterator removals must occur on the actual fastutil table.
        // Move the Arc handle, not the index state, to borrow self's heap.
        let next = Arc::clone(&self.next);
        next.lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
            .edit_entries(|key, due| {
                if due > current {
                    return Some(due);
                }
                let pos = unpack(key);
                let container = self
                    .registered
                    .contains(&key)
                    .then(|| store.get(pos))
                    .flatten()?;
                let head = container.peek()?;
                if head.trigger_tick > current {
                    return Some(head.trigger_tick);
                }
                if check(pos) {
                    self.offer_container(store, pos);
                    None
                } else {
                    Some(due)
                }
            });
        while self.can_schedule_more(max) {
            let Some(pos) = self.poll_container(store) else {
                break;
            };
            self.to_run
                .push_back(store.get_mut(pos).unwrap().poll().unwrap());
            if self.can_schedule_more(max) {
                let next_best = self
                    .containers_to_tick
                    .first()
                    .and_then(|pos| store.get(*pos))
                    .and_then(LevelChunkTicks::peek)
                    .cloned();
                while self.can_schedule_more(max) {
                    let Some(tick) = store.get(pos).unwrap().peek() else {
                        break;
                    };
                    if tick.trigger_tick > current
                        || next_best.as_ref().is_some_and(|next| {
                            ScheduledTick::intra_tick_drain_cmp(tick, next) == Ordering::Greater
                        })
                    {
                        break;
                    }
                    self.to_run
                        .push_back(store.get_mut(pos).unwrap().poll().unwrap());
                }
            }
            if let Some(head) = store.get(pos).unwrap().peek() {
                if head.trigger_tick <= current && self.can_schedule_more(max) {
                    self.offer_container(store, pos);
                } else {
                    self.update_container_scheduling(head);
                }
            }
        }
        for pos in &self.containers_to_tick {
            self.update_container_scheduling(store.get(*pos).unwrap().peek().unwrap());
        }
    }
    /// Output may query, clear/copy or schedule on this same scheduler and
    /// canonical store. A thrown/panicking output leaves source partial state;
    /// cleanup is deliberately not an unconditional finally operation.
    pub fn tick<S: TickContainers<T>>(
        &mut self,
        store: &mut S,
        current: i64,
        max: i32,
        check: impl FnMut(ChunkPos) -> bool,
        mut output: impl FnMut(&mut Self, &mut S, BlockPos, T),
    ) {
        self.collect_due_ticks(store, current, max, check);
        while let Some((pos, kind)) = self.next_collected_tick() {
            output(self, store, pos, kind);
        }
        self.cleanup_after_tick();
    }
    /// The collect phase of the same LevelTicks.tick algorithm. Splitting
    /// borrows lets a canonical world own this scheduler while its output
    /// calls back into that world, including reentrant schedule/clear/query.
    /// Call cleanup only after all outputs return normally: Java has no finally.
    pub fn collect_due_ticks(
        &mut self,
        store: &mut impl TickContainers<T>,
        current: i64,
        max: i32,
        check: impl FnMut(ChunkPos) -> bool,
    ) {
        self.collect_ticks(store, current, max, check);
    }
    /// Source runCollectedTicks updates membership/alreadyRun BEFORE output.
    pub fn next_collected_tick(&mut self) -> Option<(BlockPos, T)> {
        let tick = self.to_run.pop_front()?;
        if !self.to_run_set.is_empty() {
            self.to_run_set.remove(&UniqueTickKey::from(&tick));
        }
        let result = (tick.pos, tick.r#type.clone());
        self.already_run.push(tick);
        Some(result)
    }
    pub fn cleanup_after_tick(&mut self) {
        self.to_run.clear();
        self.containers_to_tick.clear();
        self.already_run.clear();
        self.to_run_set.clear();
    }
    pub fn has_scheduled_tick(
        &self,
        store: &impl TickContainers<T>,
        pos: &BlockPos,
        kind: &T,
    ) -> bool {
        let chunk = ChunkPos::containing(pos);
        self.registered.contains(&chunk.pack())
            && store
                .get(chunk)
                .is_some_and(|container| container.has_scheduled_tick(pos, kind))
    }
    pub fn will_tick_this_tick(&mut self, pos: &BlockPos, kind: &T) -> bool {
        if self.to_run_set.is_empty() && !self.to_run.is_empty() {
            self.to_run_set
                .extend(self.to_run.iter().map(UniqueTickKey::from));
        }
        self.to_run_set
            .contains(&UniqueTickKey::new(kind.clone(), *pos))
    }
    pub fn count(&self, store: &impl TickContainers<T>) -> usize {
        self.registered
            .iter()
            .filter_map(|key| store.get(unpack(*key)))
            .map(LevelChunkTicks::count)
            .sum()
    }
    fn for_containers_in_area(
        &self,
        store: &mut impl TickContainers<T>,
        area: BoundingBox,
        mut output: impl FnMut(ChunkPos, &mut LevelChunkTicks<T>),
    ) {
        for x in (area.min_x >> 4)..=(area.max_x >> 4) {
            for z in (area.min_z >> 4)..=(area.max_z >> 4) {
                let pos = ChunkPos::new(x, z);
                if self.registered.contains(&pos.pack())
                    && let Some(container) = store.get_mut(pos)
                {
                    output(pos, container);
                }
            }
        }
    }
    pub fn clear_area(&mut self, store: &mut impl TickContainers<T>, area: BoundingBox) {
        self.for_containers_in_area(store, area, |pos, container| {
            let previous = container.peek().cloned();
            container.remove_if(|tick| area.is_inside(&tick.pos));
            // removeIf cannot replace an unremoved head by a value-identical
            // different instance: if its position is inside, all such heads
            // are removed. Thus equality preserves Java's identity comparison.
            if container.peek() != previous.as_ref() {
                if let Some(head) = container.peek() {
                    self.update_container_scheduling(head);
                } else {
                    self.next
                        .lock()
                        .unwrap_or_else(|poisoned| poisoned.into_inner())
                        .remove(pos.pack());
                }
            }
        });
        self.already_run.retain(|tick| !area.is_inside(&tick.pos));
        self.to_run.retain(|tick| !area.is_inside(&tick.pos));
        // Source deliberately leaves the lazily populated query set alone.
    }
    fn ticks_in_area(
        &self,
        store: &impl TickContainers<T>,
        area: BoundingBox,
    ) -> Vec<ScheduledTick<T>> {
        let mut result: Vec<_> = self
            .already_run
            .iter()
            .chain(self.to_run.iter())
            .filter(|tick| area.is_inside(&tick.pos))
            .cloned()
            .collect();
        for x in (area.min_x >> 4)..=(area.max_x >> 4) {
            for z in (area.min_z >> 4)..=(area.max_z >> 4) {
                let pos = ChunkPos::new(x, z);
                if self.registered.contains(&pos.pack())
                    && let Some(container) = store.get(pos)
                {
                    result.extend(
                        container
                            .all()
                            .filter(|tick| area.is_inside(&tick.pos))
                            .cloned(),
                    );
                }
            }
        }
        result
    }
    fn schedule_copies(
        &mut self,
        store: &mut impl TickContainers<T>,
        ticks: Vec<ScheduledTick<T>>,
        offset: Vec3i,
    ) {
        let min = ticks
            .iter()
            .map(|tick| tick.sub_tick_order)
            .min()
            .unwrap_or(i64::MAX);
        let max = ticks
            .iter()
            .map(|tick| tick.sub_tick_order)
            .max()
            .unwrap_or(i64::MIN);
        for tick in ticks {
            self.schedule(
                store,
                ScheduledTick::new(
                    tick.r#type,
                    tick.pos.offset_vec(&offset),
                    tick.trigger_tick,
                    tick.priority,
                    tick.sub_tick_order
                        .wrapping_sub(min)
                        .wrapping_add(max)
                        .wrapping_add(1),
                ),
            );
        }
    }
    pub fn copy_area(
        &mut self,
        store: &mut impl TickContainers<T>,
        area: BoundingBox,
        offset: Vec3i,
    ) {
        let ticks = self.ticks_in_area(store, area);
        self.schedule_copies(store, ticks, offset);
    }
    pub fn copy_area_from(
        &mut self,
        store: &mut impl TickContainers<T>,
        source: &Self,
        source_store: &impl TickContainers<T>,
        area: BoundingBox,
        offset: Vec3i,
    ) {
        let ticks = source.ticks_in_area(source_store, area);
        self.schedule_copies(store, ticks, offset);
    }
}
